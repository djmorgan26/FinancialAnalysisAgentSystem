-- investment_preferences.id used to default to the literal value 1, so any
-- upsert that hit INSERT (new user) collided on the primary key. Promote to
-- an identity column so new rows auto-increment.

alter table public.investment_preferences alter column id drop default;
alter table public.investment_preferences
  alter column id add generated by default as identity;

select setval(
  pg_get_serial_sequence('public.investment_preferences', 'id'),
  coalesce((select max(id) from public.investment_preferences), 0) + 1,
  false
);
